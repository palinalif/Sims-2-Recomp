#!/usr/bin/env python3
"""Regenerate ONLY the public authored sum fixture with pinned pcrecomp.

No original executable/input is accepted. Does not fetch or patch upstream.
The sole transformation is the function signature for the checked-memory shim.
"""
import argparse
import importlib.util
from pathlib import Path
import sys
from types import SimpleNamespace
from fetch_pcrecomp import ROOT, verify
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

CODE = bytes.fromhex('8b442404034424088944240cc3')
VA = 0xA0001000
HEADER = ROOT / 'tests/fixtures/synthetic_dispatch_lift.inc'


def generate(source):
    verify(source)
    spec = importlib.util.spec_from_file_location('dispatch_pcrecomp', source / 'tools/lift/difftest.py')
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    decoder = Cs(CS_ARCH_X86, CS_MODE_32)
    decoder.detail = True
    instructions = list(decoder.disasm(CODE, VA))
    block = SimpleNamespace(start=VA, instructions=instructions)
    function = SimpleNamespace(name='synthetic_sum', address=VA, blocks={VA: block})
    lifted = module.Lifter(precise_carry=True).lift_function(function)
    old = 'void synthetic_sum(void)'
    if lifted.count(old) != 1 or 'UNIMPLEMENTED' in lifted or 'unhandled' in lifted.lower():
        raise ValueError('Unexpected upstream output')
    lifted = lifted.replace(old, 'void synthetic_sum(ts2::GuestRegisters& r, ts2::GuestMemory& m, const ts2::GuestDispatch&)')
    return ('// Public authored x86 fixture; no Sims 2 bytes. Generated by\n'
            '// tools/generate_dispatch_fixture.py, pinned pcrecomp c0cbd3e.\n'
            '// Generated templates: Copyright (c) 2026 sp00nz, MIT;\n'
            '// see third_party/pcrecomp/LICENSE.\n'
            '// Only the function signature is adapted. Do not edit the body.\n' + lifted + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pcrecomp', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(args.pcrecomp.resolve())
    if args.check:
        if HEADER.read_text() != text:
            parser.error('Committed public fixture differs from pinned lift')
    else:
        HEADER.parent.mkdir(parents=True, exist_ok=True)
        HEADER.write_text(text)
    print('Public dispatch fixture matches pinned lift' if args.check else 'Generated public dispatch fixture')


if __name__ == '__main__':
    main()
